-- Events schema
create table if not exists public.events (
	id bigint generated by default as identity primary key,
	title text not null,
	description text,
	recurrence_type text not null default 'yearly',
	start_month smallint,
	end_month smallint,
	recurrence_ordinal smallint,
	recurrence_weekday smallint,
	place_id bigint references public.places(id) on delete set null,
	website text,
	image_url text,
	image_storage_path text,
	is_published boolean not null default true,
	start_date date,
	end_date date,
	start_time time,
	end_time time,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

-- Event places
alter table public.places
add column if not exists is_event_only boolean not null default false;

alter table public.places
add column if not exists is_free boolean not null default false;

create index if not exists places_event_only_idx
on public.places(is_event_only);

-- Event fields
alter table public.events add column if not exists start_month smallint;
alter table public.events add column if not exists end_month smallint;
alter table public.events add column if not exists recurrence_ordinal smallint;
alter table public.events add column if not exists recurrence_weekday smallint;
alter table public.events add column if not exists image_url text;
alter table public.events add column if not exists image_storage_path text;

alter table public.events alter column start_date drop not null;
alter table public.events alter column recurrence_type set default 'yearly';

-- Old constraints
alter table public.events drop constraint if exists events_recurrence_type_check;
alter table public.events drop constraint if exists events_date_order_check;
alter table public.events drop constraint if exists events_schedule_check;

-- Old data
update public.events
set start_month = extract(month from start_date)::smallint
where start_month is null and start_date is not null;

update public.events
set end_month = extract(month from coalesce(end_date, start_date))::smallint
where end_month is null and start_date is not null;

update public.events
set recurrence_ordinal = (((extract(day from start_date)::int - 1) / 7) + 1)::smallint,
	recurrence_weekday = extract(dow from start_date)::smallint
where recurrence_type = 'monthly'
	and start_date is not null;

update public.events
set recurrence_type = 'monthly_rule'
where recurrence_type = 'monthly';

update public.events
set recurrence_type = 'yearly'
where recurrence_type = 'none';

update public.events
set start_month = coalesce(start_month, 1),
	end_month = coalesce(end_month, start_month, 1)
where recurrence_type = 'yearly';

update public.events
set recurrence_ordinal = coalesce(recurrence_ordinal, 1),
	recurrence_weekday = coalesce(recurrence_weekday, 6)
where recurrence_type = 'monthly_rule';

-- Constraints
alter table public.events
add constraint events_recurrence_type_check
check (recurrence_type in ('yearly', 'monthly_rule'));

alter table public.events
add constraint events_schedule_check
check (
	(
		recurrence_type = 'yearly'
		and start_month between 1 and 12
		and end_month between 1 and 12
		and recurrence_ordinal is null
		and recurrence_weekday is null
	)
	or
	(
		recurrence_type = 'monthly_rule'
		and recurrence_ordinal in (-1, 1, 2, 3, 4, 5)
		and recurrence_weekday between 0 and 6
	)
);

-- Indexes
create index if not exists events_start_month_idx on public.events(start_month);
create index if not exists events_recurrence_type_idx on public.events(recurrence_type);
create index if not exists events_place_id_idx on public.events(place_id);
create index if not exists events_published_idx on public.events(is_published);

-- Permissions
alter table public.events enable row level security;

grant select on public.events to anon;
grant select, insert, update, delete on public.events to authenticated;
grant usage, select on sequence public.events_id_seq to authenticated;

-- Policies
drop policy if exists "Public can read published events" on public.events;
drop policy if exists "Only admin can manage events" on public.events;

create policy "Public can read published events"
on public.events
for select
to anon, authenticated
using (is_published = true);


-- Events table
create table if not exists public.events (
	id bigint generated by default as identity primary key,
	title text not null,
	description text,
	start_date date not null,
	end_date date,
	start_time time,
	end_time time,
	recurrence_type text not null default 'none',
	place_id bigint references public.places(id) on delete set null,
	website text,
	is_published boolean not null default true,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	constraint events_recurrence_type_check check (recurrence_type in ('none', 'yearly', 'monthly')),
	constraint events_date_order_check check (end_date is null or end_date >= start_date)
);

create index if not exists events_start_date_idx on public.events(start_date);
create index if not exists events_place_id_idx on public.events(place_id);
create index if not exists events_published_idx on public.events(is_published);

-- Permissions
alter table public.events enable row level security;

grant select on public.events to anon;
grant select, insert, update, delete on public.events to authenticated;
grant usage, select on sequence public.events_id_seq to authenticated;

-- Policies
drop policy if exists "Public can read published events" on public.events;
drop policy if exists "Only admin can manage events" on public.events;

create policy "Public can read published events"
on public.events
for select
to anon, authenticated
using (is_published = true);

create policy "Only admin can manage events"
on public.events
for all
to authenticated
using (auth.uid() = 'df168eb9-7131-4b74-b757-75f6a653e299')
with check (auth.uid() = 'df168eb9-7131-4b74-b757-75f6a653e299');
